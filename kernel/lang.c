static VfsNode* lang_preferences_file(void) {
    VfsNode* file = vfs_resolve(vfs_root(), "/etc/haos.lang");
    if (file) return file;

    VfsNode* etc = vfs_resolve(vfs_root(), "/etc");
    return etc ? vfs_touch(etc, "haos.lang") : NULL;
}

